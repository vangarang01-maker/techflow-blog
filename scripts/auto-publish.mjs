/* -------------------------------------------------------------- rendering */

function renderTable(table) {
  const lines = [
    `| ${table.headers.join(' | ')} |`,
    `| ${table.headers.map(() => '---').join(' | ')} |`,
    ...table.rows.map((row) => `| ${row.join(' | ')} |`),
  ];
  return lines.join('\n');
}

/** Deterministic renderer — the fallback path and the shape Gemini imitates. */
function renderBody(topic) {
  const out = [];

  out.push(topic.hook, '');

  out.push('**이 글에서 다루는 내용**', '');
  topic.steps.forEach((step, index) => out.push(`${index + 1}. ${step.h}`));
  out.push('');

  out.push('## 왜 지금 정리해야 할까요', '');
  for (const reason of topic.why) out.push(`- ${reason}`);
  out.push('');

  out.push('## 시작 전 준비물', '');
  for (const item of topic.prep) out.push(`- ${item}`);
  out.push('');

  out.push('## 단계별 실행 가이드', '');
  topic.steps.forEach((step, index) => {
    out.push(`### ${index + 1}단계 — ${step.h}`, '');
    out.push(step.b, '');
    if (step.tip) out.push(`> **팁:** ${step.tip}`, '');
  });

  out.push(`## ${topic.table.title}`, '');
  out.push(renderTable(topic.table), '');

  out.push('## 실전 프로 팁', '');
  for (const tip of topic.tips) out.push(`- ${tip}`);
  out.push('');

  if (topic.deepDive) {
    out.push(`## ${topic.deepDive.title}`, '');
    for (const paragraph of topic.deepDive.paragraphs) out.push(paragraph, '');
  }

  out.push('## 자주 겪는 문제와 해결법', '');
  for (const item of topic.faq) {
    out.push(`### Q. ${item.q}`, '');
    out.push(`**A.** ${item.a}`, '');
  }

  out.push('## 마무리 체크리스트', '');
  for (const step of topic.steps) out.push(`- [ ] ${step.h}`);
  out.push('');

  out.push(topic.closing, '');

  return out.join('\n').trim();
}

