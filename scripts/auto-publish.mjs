/** Optional Gemini draft. Any failure returns null so the template takes over. */
async function generateWithGemini(topic) {
  const apiKey = process.env.GEMINI_API_KEY;
  if (!apiKey) return null;

  const selectedPattern = selectWritingPattern(topic);
  console.log(`[pattern] 🎨 Selected IT writing pattern: "${selectedPattern.name}" (${selectedPattern.id})`);

  const outline = JSON.stringify(
    {
      title: topic.title,
      description: topic.description,
      category: topic.category,
      tags: topic.tags,
      sections: {
        hook: topic.hook,
        why: topic.why,
        prep: topic.prep,
        steps: topic.steps,
        table: topic.table,
        tips: topic.tips,
        faq: topic.faq,
        deepDive: topic.deepDive,
        closing: topic.closing,
      },
    },
    null,
    2,
  );

  const candidateModels = Array.from(
    new Set([
      GEMINI_MODEL,
      'gemini-3.7-flash',
      'gemini-3.6-flash',
      'gemini-3.5-flash',
    ]),
  );

  for (const model of candidateModels) {
    const url = `https://generativelanguage.googleapis.com/v1beta/models/${model}:generateContent`;

    try {
      const response = await fetch(url, {
        method: 'POST',
        headers: { 'content-type': 'application/json', 'x-goog-api-key': apiKey },
        body: JSON.stringify({
          contents: [
            {
              role: 'user',
              parts: [
                {
                  text: `${GEMINI_INSTRUCTIONS}\n\n${selectedPattern.instruction}\n\n개요:\n${outline}`,
                },
              ],
            },
          ],
          generationConfig: { temperature: 0.7, maxOutputTokens: 8192 },
        }),
        signal: AbortSignal.timeout(90_000),
      });

      if (!response.ok) {
        console.warn(`[gemini] ${model} HTTP ${response.status} — trying next model`);
        continue;
      }

      const payload = await response.json();
      const candidate = payload?.candidates?.[0];
      const finishReason = candidate?.finishReason;

      if (finishReason && finishReason !== 'STOP') {
        console.warn(`[gemini] ${model} incomplete finishReason (${finishReason}) — trying next model`);
        continue;
      }

      const text = (candidate?.content?.parts ?? [])
        .map((part) => part.text ?? '')
        .join('')
        .trim();

      const cleaned = normalizeMarkdown(
        text
          .replace(/^```(?:markdown|md)?\s*\n?/i, '')
          .replace(/\n?```\s*$/i, '')
          .replace(/^---[\s\S]*?---\s*/, '')
          .trim()
      );

      if (cleaned.length < MIN_CHARS) {
        console.warn(`[gemini] ${model} draft too short (${cleaned.length} chars) — trying next model`);
        continue;
      }

      console.log(`[gemini] successfully generated via ${model}!`);
      return cleaned;
    } catch (error) {
      console.warn(`[gemini] ${model} error: ${error.message} — trying next model`);
    }
  }

  console.warn(`[gemini] all candidate models failed — falling back to template`);
  return null;
}

function normalizeMarkdown(text) {
  return text
    // Fix **"text"** or **“text”** to “**text**” (so quotes don't break CommonMark bold parsing)
    .replace(/\*\*["“](.*?)[”"]\*\*/g, '“**$1**”')
    .replace(/\*\*['‘](.*?)[’']\*\*/g, '‘**$1**’')
    .replace(/\*\*\s*\*\*/g, '')
    // Fix accidental strikethrough caused by ~ used for ranges (e.g. 2~3칸, 10~20%)
    .replace(/(\d+)\s*~\s*(\d+)/g, '$1～$2')
    .replace(/~\s*(\d+)/g, '～$1');
}

function getKstDateString() {
  const formatter = new Intl.DateTimeFormat('ko-KR', {
    timeZone: 'Asia/Seoul',
    year: 'numeric',
    month: '2-digit',
    day: '2-digit',
  });
  const parts = formatter.formatToParts(new Date());
  const year = parts.find((p) => p.type === 'year')?.value;
  const month = parts.find((p) => p.type === 'month')?.value;
  const day = parts.find((p) => p.type === 'day')?.value;
  return `${year}-${month}-${day}`;
}

function renderFrontmatter(topic, pubDate) {
  return [
    '---',
    `title: ${yamlString(topic.title)}`,
    `description: ${yamlString(topic.description)}`,
    `pubDate: ${yamlString(pubDate)}`,
    `category: ${yamlString(topic.category)}`,
    `tags: ${yamlList(topic.tags)}`,
    `author: ${yamlString(AUTHOR)}`,
    'draft: false',
    '---',
  ].join('\n');
}

/* ------------------------------------------------------------------- main */

async function main() {
  const args = process.argv.slice(2);
  const dryRun = args.includes('--dry-run');
  const slugArgIndex = args.indexOf('--slug');
  const forcedSlug = slugArgIndex !== -1 ? args[slugArgIndex + 1] : undefined;

  const existing = await readExisting();
  const { topic, fresh } = await selectTopic(existing, forcedSlug);

  if (!CATEGORIES.includes(topic.category)) {
    throw new Error(`Category "${topic.category}" is not in the content schema enum.`);
  }
  if (!forcedSlug && existing.slugs.has(topic.slug)) {
    throw new Error(`Refusing to overwrite existing post: ${topic.slug}.md`);
  }

  let body = await generateWithGemini(topic);
  const source = body ? 'gemini' : 'template';
  if (!body) body = renderBody(topic);

  if (body.length < MIN_CHARS) {
    throw new Error(`Generated body is ${body.length} chars, below the ${MIN_CHARS} minimum.`);
  }

  const pubDate = getKstDateString();
  const markdown = `${renderFrontmatter(topic, pubDate)}\n\n${body}\n`;
  const filename = `${topic.slug}.md`;
  const filePath = path.join(BLOG_DIR, filename);

  const stats = {
    file: path.relative(ROOT, filePath),
    filename,
    slug: topic.slug,
    title: topic.title,
    category: topic.category,
    tags: topic.tags,
    pubDate,
    source,
    freshTopic: fresh,
    bodyChars: body.length,
    totalChars: markdown.length,
    headings: (body.match(/^#{2,3} /gm) ?? []).length,
    existingPosts: existing.count,
    remainingTopics: TOPICS.filter((entry) => !existing.slugs.has(entry.slug)).length - 1,
  };

  if (!dryRun) {
    await writeFile(filePath, markdown, 'utf8');
    if (process.env.GITHUB_OUTPUT) {
      await appendFile(
        process.env.GITHUB_OUTPUT,
        `created=true\nfile=${stats.file}\nslug=${stats.slug}\ntitle=${stats.title}\n`,
        'utf8',
      );
    }
  }

  console.log(`${dryRun ? '[dry-run] would write' : 'wrote'} ${stats.file}`);
  console.log(`  title    : ${stats.title}`);
  console.log(`  category : ${stats.category}  tags: ${stats.tags.join(', ')}`);
  console.log(`  source   : ${stats.source}${fresh ? ' (freshly minted topic)' : ''}`);
  console.log(`  size     : ${stats.bodyChars} body chars, ${stats.headings} headings`);
  console.log(`  bank     : ${stats.remainingTopics} curated topics left, ${stats.existingPosts} posts already published`);
  console.log(JSON.stringify(stats));

  return stats;
}

main().catch((error) => {
  console.error(`[auto-publish] ${error.stack ?? error.message}`);
  process.exitCode = 1;
});
