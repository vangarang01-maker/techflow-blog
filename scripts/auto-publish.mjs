/** Reads every published post so we never reuse a slug or a title. */
async function readExisting() {
  let entries = [];
  try {
    entries = await readdir(BLOG_DIR);
  } catch (error) {
    if (error.code !== 'ENOENT') throw error;
  }

  const files = entries.filter((name) => /\.mdx?$/.test(name));
  const slugs = new Set(files.map((name) => name.replace(/\.mdx?$/, '')));
  const titles = new Set();

  for (const name of files) {
    const raw = await readFile(path.join(BLOG_DIR, name), 'utf8');
    const match = raw.match(/^---\r?\n([\s\S]*?)\r?\n---/);
    if (!match) continue;
    const titleLine = match[1].match(/^title:\s*(.+)$/m);
    if (titleLine) {
      titles.add(normalizeTitle(titleLine[1].trim().replace(/^["']|["']$/g, '')));
    }
  }

  return { slugs, titles, count: files.length };
}

/** Picks the first curated topic that has not been published yet. */
async function selectTopic({ slugs, titles }, forcedSlug) {
  if (forcedSlug) {
    const forced = TOPICS.find((topic) => topic.slug === forcedSlug);
    if (!forced) throw new Error(`Unknown topic slug: ${forcedSlug}`);
    return { topic: forced, fresh: false };
  }

  const unwritten = TOPICS.filter(
    (topic) => !slugs.has(topic.slug) && !titles.has(normalizeTitle(topic.title)),
  );

  if (unwritten.length > 0) {
    // Rotate by day-of-year so consecutive runs vary category instead of
    // publishing the whole bank in bank order.
    const dayIndex = Math.floor(Date.now() / 86_400_000);
    return { topic: unwritten[dayIndex % unwritten.length], fresh: false };
  }

  const freshTopic = await mintFreshTopic({ slugs, titles });
  return { topic: freshTopic, fresh: true };
}

/** Generates a new, 100% unique topic once the curated bank is exhausted via Gemini. */
async function mintFreshTopic({ slugs, titles }) {
  const dynamicTopic = await inventFreshTopicWithGemini({ slugs, titles });
  if (dynamicTopic) {
    return dynamicTopic;
  }

  for (const angle of ANGLES) {
    for (const base of TOPICS) {
      const slug = `${base.slug}-${angle.key}`;
      const title = `${base.title}${angle.titleSuffix}`;
      if (slugs.has(slug) || titles.has(normalizeTitle(title))) continue;
      return {
        ...base,
        slug,
        title,
        description: `${angle.lead} ${base.description}`.slice(0, 295),
        hook: `${angle.lead}\n\n${base.hook}`,
      };
    }
  }

  // Safe fallback without duplicate version suffixes
  const base = TOPICS[Math.floor(Math.random() * TOPICS.length)];
  const timestamp = Date.now().toString().slice(-4);
  return {
    ...base,
    slug: `${base.slug}-${timestamp}`,
    title: `${base.title} — 실전 심층 가이드`,
  };
}

