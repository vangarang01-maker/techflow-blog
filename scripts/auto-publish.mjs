const normalizeTitle = (value) =>
  value
    .toLowerCase()
    .replace(/[\s\p{P}\p{S}]/gu, '')
    .trim();

const yamlString = (value) => `"${String(value).replace(/\\/g, '\\\\').replace(/"/g, '\\"')}"`;

